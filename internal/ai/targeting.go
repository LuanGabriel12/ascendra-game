package ai

import (
	"fmt"
	"math/bits"
	"strings"
)

// TargetKind classifies perceivable combat/objective targets.
type TargetKind string

const (
	TargetNone       TargetKind = ""
	TargetSettlement TargetKind = "Settlement"
	TargetDefender   TargetKind = "Defender"
)

// Valid reports whether the target kind is known.
func (k TargetKind) Valid() bool {
	return k == TargetSettlement || k == TargetDefender
}

// Code returns a stable canonical integer code for checksum hashing.
func (k TargetKind) Code() uint8 {
	switch k {
	case TargetSettlement:
		return 1
	case TargetDefender:
		return 2
	default:
		return 0
	}
}

// TargetRef uniquely identifies a target by combining Kind and ID so that
// a Settlement and a Defender sharing identical text cannot collide semantically.
type TargetRef struct {
	Kind TargetKind `json:"kind"`
	ID   string     `json:"id"`
}

// IsZero reports whether the target reference is unset.
func (r TargetRef) IsZero() bool {
	return r.Kind == TargetNone && r.ID == ""
}

// Valid reports whether the target reference is either unset or fully well-formed.
func (r TargetRef) Valid() bool {
	if r.IsZero() {
		return true
	}
	return r.Kind.Valid() && strings.TrimSpace(r.ID) != ""
}

// PerceivedTarget is an explicit, immutable data snapshot of a potential target.
type PerceivedTarget struct {
	TargetID    string
	Kind        TargetKind
	Position    int64 // WorldUnit >= 0
	HP          int64
	MaxHP       int64
	ThreatScore int64 // >= 0 authoritative threat generated by this target
}

// Ref returns the typed TargetRef for this perceived target.
func (t PerceivedTarget) Ref() TargetRef {
	return TargetRef{Kind: t.Kind, ID: t.TargetID}
}

// Validate enforces invariants on a perceived target.
func (t PerceivedTarget) Validate() error {
	if strings.TrimSpace(t.TargetID) == "" {
		return fmt.Errorf("%w: empty target_id", ErrInvalidPerception)
	}
	if !t.Kind.Valid() {
		return fmt.Errorf("%w: unknown target kind %q", ErrInvalidPerception, t.Kind)
	}
	if t.Position < 0 {
		return fmt.Errorf("%w: negative target position %d", ErrInvalidPerception, t.Position)
	}
	if t.MaxHP <= 0 || t.HP < 0 || t.HP > t.MaxHP {
		return fmt.Errorf("%w: target %q hp %d out of [0, %d]", ErrInvalidPerception, t.TargetID, t.HP, t.MaxHP)
	}
	if t.ThreatScore < 0 {
		return fmt.Errorf("%w: target %q negative threat %d", ErrInvalidPerception, t.TargetID, t.ThreatScore)
	}
	return nil
}

// TargetSelection holds the deterministic winner of target scoring.
type TargetSelection struct {
	TargetID string
	Kind     TargetKind
	Position int64
	Distance int64
	Score    int64
}

// Ref returns the typed TargetRef of the selected target.
func (s TargetSelection) Ref() TargetRef {
	return TargetRef{Kind: s.Kind, ID: s.TargetID}
}

// TargetMemoryOptions configures optional target retention hysteresis (Cycle 03).
type TargetMemoryOptions struct {
	RetainedTarget TargetRef
	RetentionBonus int64
}

// SelectTarget evaluates visible and siege-relevant targets using pure integer weights
// from Profile and optional collective CoordinationOrder focus.
// Tie-breaking is deterministic: highest Score -> smallest Distance -> TargetKind -> TargetID.
func SelectTarget(
	selfPos int64,
	homePos int64,
	profile Profile,
	targets []PerceivedTarget,
	order CoordinationOrder,
	invasionActive bool,
) (TargetSelection, bool) {
	return SelectTargetWithMemory(selfPos, homePos, profile, targets, order, invasionActive, TargetMemoryOptions{})
}

// SelectTargetWithMemory evaluates targets with an optional retention bonus for an
// existing live target to prevent rapid target flickering.
func SelectTargetWithMemory(
	selfPos int64,
	homePos int64,
	profile Profile,
	targets []PerceivedTarget,
	order CoordinationOrder,
	invasionActive bool,
	mem TargetMemoryOptions,
) (TargetSelection, bool) {
	var best TargetSelection
	found := false

	maxRange := profile.VisionRange
	if profile.AlertRange > maxRange {
		maxRange = profile.AlertRange
	}
	if maxRange <= 0 {
		maxRange = 1
	}

	focusRef := order.FocusTarget
	if focusRef.IsZero() && order.TargetID != "" {
		// Backward compatibility when callers populate TargetID without FocusTarget.
		focusRef = TargetRef{ID: order.TargetID}
	}

	for _, t := range targets {
		if t.HP <= 0 {
			continue
		}
		dist := absDiffInt64(selfPos, t.Position)
		matchesFocus := !focusRef.IsZero() && t.TargetID == focusRef.ID && (focusRef.Kind == TargetNone || focusRef.Kind == t.Kind)

		visible := dist <= profile.VisionRange
		if !visible && matchesFocus && dist <= profile.AlertRange {
			visible = true
		}
		if !visible && invasionActive && t.Kind == TargetSettlement {
			visible = true
		}
		if !visible {
			continue
		}
		if !invasionActive && t.Kind == TargetSettlement {
			continue
		}
		if !invasionActive && absDiffInt64(t.Position, homePos) > profile.LeashRadius {
			continue
		}

		// 1. Proximity component: 0..1000
		proxNorm := int64(0)
		if dist < maxRange {
			proxNorm = ((maxRange - dist) * 1000) / maxRange
		}
		score := proxNorm * profile.WeightProximity

		// 2. Low-HP opportunistic component: missingHP / maxHP in 0..1000 (128-bit safe).
		missingHP := t.MaxHP - t.HP
		lowHPNorm := ratioPermille(missingHP, t.MaxHP)
		score += lowHPNorm * profile.WeightLowHP

		// 3. Threat component: clamped to 0..1000.
		threatNorm := t.ThreatScore
		if threatNorm > 1000 {
			threatNorm = 1000
		}
		score += threatNorm * profile.WeightThreat

		// 4. Objective component (settlement target during invasion).
		if t.Kind == TargetSettlement && invasionActive {
			score += 1000 * profile.WeightObjective
		}

		// 5. Collective commander/pack focus bonus (typed match avoids Settlement/Defender collision).
		if matchesFocus {
			score += 1000 * profile.WeightCommanderFocus
		}

		// 6. Optional target retention bonus while target remains valid and visible.
		if mem.RetentionBonus > 0 && !mem.RetainedTarget.IsZero() && mem.RetainedTarget == t.Ref() {
			score += mem.RetentionBonus
		}

		cand := TargetSelection{
			TargetID: t.TargetID,
			Kind:     t.Kind,
			Position: t.Position,
			Distance: dist,
			Score:    score,
		}
		if !found || isBetterTarget(cand, best) {
			best = cand
			found = true
		}
	}

	return best, found
}

func isBetterTarget(a, b TargetSelection) bool {
	if a.Score != b.Score {
		return a.Score > b.Score
	}
	if a.Distance != b.Distance {
		return a.Distance < b.Distance
	}
	if a.TargetID != b.TargetID {
		return a.TargetID < b.TargetID
	}
	return a.Kind < b.Kind
}

func absDiffInt64(a, b int64) int64 {
	if a >= b {
		return a - b
	}
	return b - a
}

// ratioPermille computes floor((num * 1000) / den) safely for any non-negative int64.
func ratioPermille(num, den int64) int64 {
	if num <= 0 || den <= 0 {
		return 0
	}
	if num >= den {
		return 1000
	}
	hi, lo := bits.Mul64(uint64(num), 1000)
	q, _ := bits.Div64(hi, lo, uint64(den))
	if q > 1000 {
		return 1000
	}
	return int64(q)
}
