package ai

import (
	"fmt"
	"math/bits"
	"strings"
)

// TargetKind classifies perceivable combat/objective targets.
type TargetKind string

const (
	TargetNone       TargetKind = ""
	TargetSettlement TargetKind = "Settlement"
	TargetDefender   TargetKind = "Defender"
)

// Valid reports whether the target kind is known.
func (k TargetKind) Valid() bool {
	return k == TargetSettlement || k == TargetDefender
}

// PerceivedTarget is an explicit, immutable data snapshot of a potential target.
type PerceivedTarget struct {
	TargetID    string
	Kind        TargetKind
	Position    int64 // WorldUnit >= 0
	HP          int64
	MaxHP       int64
	ThreatScore int64 // >= 0 authoritative threat generated by this target
}

// Validate enforces invariants on a perceived target.
func (t PerceivedTarget) Validate() error {
	if strings.TrimSpace(t.TargetID) == "" {
		return fmt.Errorf("%w: empty target_id", ErrInvalidPerception)
	}
	if !t.Kind.Valid() {
		return fmt.Errorf("%w: unknown target kind %q", ErrInvalidPerception, t.Kind)
	}
	if t.Position < 0 {
		return fmt.Errorf("%w: negative target position %d", ErrInvalidPerception, t.Position)
	}
	if t.MaxHP <= 0 || t.HP < 0 || t.HP > t.MaxHP {
		return fmt.Errorf("%w: target %q hp %d out of [0, %d]", ErrInvalidPerception, t.TargetID, t.HP, t.MaxHP)
	}
	if t.ThreatScore < 0 {
		return fmt.Errorf("%w: target %q negative threat %d", ErrInvalidPerception, t.TargetID, t.ThreatScore)
	}
	return nil
}

// TargetSelection holds the deterministic winner of target scoring.
type TargetSelection struct {
	TargetID string
	Kind     TargetKind
	Position int64
	Distance int64
	Score    int64
}

// SelectTarget evaluates visible and siege-relevant targets using pure integer weights
// from Profile and optional collective CoordinationOrder focus.
// Tie-breaking is deterministic: highest Score -> smallest Distance -> smallest TargetID.
func SelectTarget(
	selfPos int64,
	homePos int64,
	profile Profile,
	targets []PerceivedTarget,
	order CoordinationOrder,
	invasionActive bool,
) (TargetSelection, bool) {
	var best TargetSelection
	found := false

	maxRange := profile.VisionRange
	if profile.AlertRange > maxRange {
		maxRange = profile.AlertRange
	}
	if maxRange <= 0 {
		maxRange = 1
	}

	for _, t := range targets {
		if t.HP <= 0 {
			continue
		}
		dist := absDiffInt64(selfPos, t.Position)

		// Visibility & relevance gate:
		// - Settlement is always perceived during an active invasion assault.
		// - Commander/pack focus targets are perceived up to AlertRange.
		// - Other targets must be within VisionRange (and when outside an active invasion,
		//   targets outside the territorial leash are ignored unless already in VisionRange).
		visible := dist <= profile.VisionRange
		if !visible && order.TargetID != "" && t.TargetID == order.TargetID && dist <= profile.AlertRange {
			visible = true
		}
		if !visible && invasionActive && t.Kind == TargetSettlement {
			visible = true
		}
		if !visible {
			continue
		}
		// Outside an active invasion, creatures only care about intruders inside their leash or vision.
		if !invasionActive && t.Kind == TargetSettlement {
			continue
		}
		if !invasionActive && absDiffInt64(t.Position, homePos) > profile.LeashRadius {
			continue
		}

		// 1. Proximity component: 0..1000
		proxNorm := int64(0)
		if dist < maxRange {
			proxNorm = ((maxRange - dist) * 1000) / maxRange
		}
		score := proxNorm * profile.WeightProximity

		// 2. Low-HP opportunistic component: missingHP / maxHP in 0..1000 (128-bit safe).
		missingHP := t.MaxHP - t.HP
		lowHPNorm := ratioPermille(missingHP, t.MaxHP)
		score += lowHPNorm * profile.WeightLowHP

		// 3. Threat component: clamped to 0..1000.
		threatNorm := t.ThreatScore
		if threatNorm > 1000 {
			threatNorm = 1000
		}
		score += threatNorm * profile.WeightThreat

		// 4. Objective component (settlement target during invasion).
		if t.Kind == TargetSettlement && invasionActive {
			score += 1000 * profile.WeightObjective
		}

		// 5. Collective commander/pack focus bonus.
		if order.TargetID != "" && t.TargetID == order.TargetID {
			score += 1000 * profile.WeightCommanderFocus
		}

		cand := TargetSelection{
			TargetID: t.TargetID,
			Kind:     t.Kind,
			Position: t.Position,
			Distance: dist,
			Score:    score,
		}
		if !found || isBetterTarget(cand, best) {
			best = cand
			found = true
		}
	}

	return best, found
}

func isBetterTarget(a, b TargetSelection) bool {
	if a.Score != b.Score {
		return a.Score > b.Score
	}
	if a.Distance != b.Distance {
		return a.Distance < b.Distance
	}
	return a.TargetID < b.TargetID
}

func absDiffInt64(a, b int64) int64 {
	if a >= b {
		return a - b
	}
	return b - a
}

// ratioPermille computes floor((num * 1000) / den) safely for any non-negative int64.
func ratioPermille(num, den int64) int64 {
	if num <= 0 || den <= 0 {
		return 0
	}
	hi, lo := bits.Mul64(uint64(num), 1000)
	q, _ := bits.Div64(hi, lo, uint64(den))
	if q > 1000 {
		return 1000
	}
	return int64(q)
}
